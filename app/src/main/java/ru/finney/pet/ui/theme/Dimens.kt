package ru.finney.pet.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

// Толщины обводок и радиусы скруглений одним местом. Раньше они стояли числами
// по месту использования, и в проекте разом жили шесть разных обводок
// (2, 3, 4, 5 dp и два коэффициента от размера) — на глаз это читалось как
// небрежность, потому что в макете обводка у всего одна и та же.

/**
 * Обводка — **1/12 высоты элемента**.
 *
 * Замерено по эталонам: в `Frame 3.png` (кнопка 420 × 120) обводка ровно
 * 10 пикселей, в панели «Настройки» из кадра UI-кита (638 × 430) — тоже 10.
 * Формула «15 × кегль / 200» из ранних заметок этому не соответствует;
 * при расхождении верить кадру.
 */
const val FinneyStrokeRatio = 1f / 12f

/** Обводка для элемента известной высоты. Основной способ задать обводку. */
fun strokeFor(height: Dp): Dp = height * FinneyStrokeRatio

// Для элементов, у которых высота заранее не известна (карточки по содержимому,
// поля ввода), — три ступени вместо произвольных чисел.

/** Тонкая: невыбранные карточки и второстепенные рамки. */
val StrokeThin = 2.dp

/** Обычная: карточки, поля ввода, шкалы. */
val StrokeRegular = 3.dp

/** Толстая: выбранное состояние, панели, кнопки. */
val StrokeBold = 5.dp

// Радиусы. В макете панель скруглена умеренно (≈30 px при высоте 430 — это
// не «стадион»), а кнопка — ровно в половину высоты.

/** Панели и диалоги. */
val RadiusPanel = 28.dp

/** Карточки внутри экрана. */
val RadiusCard = 20.dp

/** Поля ввода и вдавленные полосы. */
val RadiusField = 16.dp

/** Чекбокс — маленький скруглённый квадрат. */
val RadiusCheckbox = 8.dp
