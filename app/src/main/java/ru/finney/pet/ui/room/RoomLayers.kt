package ru.finney.pet.ui.room

import androidx.annotation.DrawableRes
import androidx.compose.runtime.Immutable
import ru.finney.pet.R

/**
 * Прямоугольник в долях холста комнаты: 0 — левый верхний угол, 1 — правый нижний.
 *
 * Доли, а не пиксели, потому что слои в ресурсах обрезаны по содержимому и своих
 * координат не помнят: положение живёт здесь. Тот же приём, что у точек вращения
 * конечностей в PetSkin.
 */
@Immutable
data class RelRect(val left: Float, val top: Float, val right: Float, val bottom: Float) {
    val width: Float get() = right - left
    val height: Float get() = bottom - top
}

/** Слой комнаты: картинка и место, где она лежит на холсте. */
@Immutable
data class RoomLayer(@DrawableRes val image: Int, val rect: RelRect)

/**
 * Что сейчас стоит в комнате.
 *
 * Комната одна, а предмет в ней меняется по нижней кнопке — так подписано
 * в макете главного экрана: «кухня (при нажатии на кнопку появляется стол)»,
 * «ванная (при нажатии на кнопку появляется ванна)». Поэтому стол и ванна
 * и лежат на холсте дизайнера в одном месте: показывать их вместе никто
 * и не собирался.
 */
enum class RoomSpot {
    /** Пустая комната: питомец на полу. Сюда же встанет сон, когда появится свет. */
    LIVING,

    /** Стол: здесь кормят. */
    KITCHEN,

    /** Ванна с пеной: здесь моют. */
    BATH,
}

/**
 * Комната: где что стоит.
 *
 * Все числа напечатаны `tools/pack_room.py` при сборке ресурсов и вставлены сюда
 * как есть. На глаз их не правят: слой в ресурсах обрезан ровно по этим границам,
 * и любая ручная подгонка сдвинет предмет относительно собственной картинки.
 * Дизайнер прислал новый экспорт — перезапустить скрипт и заменить блок целиком.
 */
object Room {

    /** Холст дизайнера. Сцена всегда рисуется в этой пропорции, иначе предметы разъедутся. */
    const val CANVAS_RATIO = 1440f / 2400f

    /**
     * Ось комнаты: середина пола в перспективе.
     *
     * Найдена по доскам, а не по холсту: доски сходятся к одной точке, и та,
     * что идёт строго вертикально, стоит на 0.508 на всех строках пола. На неё
     * встают и питомец в зале, и середина кадра: центральная доска уходит
     * вглубь ровно у него из-под ног, и он стоит посреди комнаты.
     */
    const val ROOM_AXIS_X = 0.508f

    /**
     * Левее этой доли холста кадр не срезает: это левый борт ванны.
     *
     * Холст заполняет экран по высоте, и на телефонах от его ширины видно
     * 0.75–0.81 — по оси комнаты ([ROOM_AXIS_X]) слева не хватает места.
     * Кадр тогда останавливается здесь, и питомец стоит чуть правее середины
     * экрана, зато целы ванна и торшер: у торшера срезается только кончик
     * кольца «Сатурна», шар абажура и подставка начинаются от 0.07.
     */
    const val FRAME_MIN_LEFT = 0.0611f

    /**
     * Шов стены и пола: выше — обои, ниже — доска.
     *
     * Найден построчным доминирующим цветом, а не на глаз: узор ёлочки чередует
     * два зелёных, и переход легко спутать с очередной полосой узора.
     */
    const val FLOOR_TOP = 0.4383f

    val Back = RoomLayer(R.drawable.room_back, RelRect(0.0000f, 0.0000f, 1.0000f, 1.0000f))
    val WindowView = RoomLayer(R.drawable.room_window_view, RelRect(0.4278f, 0.0854f, 0.8806f, 0.3542f))
    val WindowUfo = RoomLayer(R.drawable.room_window_ufo, RelRect(0.4924f, 0.2525f, 0.5979f, 0.3017f))
    val WindowFrame = RoomLayer(R.drawable.room_window_frame, RelRect(0.3500f, 0.0312f, 0.9792f, 0.3675f))
    val Lamp = RoomLayer(R.drawable.room_lamp, RelRect(0.0326f, 0.0408f, 0.2729f, 0.5262f))
    val Table = RoomLayer(R.drawable.room_table, RelRect(0.0965f, 0.5975f, 0.7757f, 0.8087f))
    val Bath = RoomLayer(R.drawable.room_bath, RelRect(0.0611f, 0.6192f, 0.7715f, 0.8433f))
    val BathFoamBack = RoomLayer(R.drawable.room_bath_foam_back, RelRect(0.0972f, 0.5271f, 0.7069f, 0.6671f))
    val BathFoamFront = RoomLayer(R.drawable.room_bath_foam_front, RelRect(0.4049f, 0.5754f, 0.7868f, 0.6587f))

    /**
     * Сторона квадрата питомца — доля ширины холста.
     *
     * Одна на все комнаты: персонаж не может менять рост, переходя из зала
     * в ванну. Размер взят от ванны — самого крупного предмета: чаша занимает
     * 0.71 ширины, силуэт питомца — 0.93 своего квадрата, то есть при 0.65
     * он заполняет чашу почти целиком и в комнате читается как главный герой,
     * а не как предмет обстановки.
     */
    const val PET_SIZE = 0.65f

    /**
     * Верх квадрата питомца в каждой комнате — доля высоты холста.
     *
     * Единственные числа в файле, снятые не замером: питомца в экспортах
     * обстановки нет и промерять нечего. Но привязаны они к замеренным
     * границам предметов. В силуэте ступни приходятся примерно на 0.87 высоты
     * квадрата, макушка — на 0.12, отсюда и отсчёт.
     */
    private fun petTop(spot: RoomSpot): Float = when (spot) {
        // По центру экрана по вертикали (0.5), а не свободного места между
        // интерфейсом сверху и кнопками снизу — от него силуэт съезжал к низу
        // и читался как стоящий у нижнего края.
        RoomSpot.LIVING -> 0.305f

        // Стол непрозрачен ниже своей кромки 0.5975 — за ней прячется нижняя
        // треть питомца, и получается, что он сидит за столом. Выше зала
        // ровно настолько, чтобы столешница пришлась под морду, а не по глаза.
        RoomSpot.KITCHEN -> 0.320f

        // Чаша перекрывает всё ниже 0.664 (борт 0.619 плюс кромка), поэтому
        // над водой остаётся примерно три четверти силуэта.
        RoomSpot.BATH -> 0.403f
    }

    /** Середина питомца по горизонтали — доля ширины холста. */
    private fun petCentre(spot: RoomSpot): Float = when (spot) {
        RoomSpot.LIVING -> ROOM_AXIS_X
        RoomSpot.KITCHEN -> 0.436f // середина стола: 0.0965..0.7757
        RoomSpot.BATH -> 0.416f // середина чаши: 0.0611..0.7715
    }

    /**
     * Где стоит питомец в текущей комнате.
     *
     * Питомец рисуется квадратом по ширине холста, поэтому работают `left`,
     * `top` и `width`; `bottom` считается тут же, чтобы прямоугольник не врал.
     */
    fun petGround(spot: RoomSpot): RelRect {
        val centre = petCentre(spot)
        val top = petTop(spot)
        return RelRect(
            left = centre - PET_SIZE / 2f,
            top = top,
            right = centre + PET_SIZE / 2f,
            // Квадрат по ширине: в долях высоты его сторона меньше во столько же
            // раз, во сколько холст выше своей ширины.
            bottom = top + PET_SIZE * CANVAS_RATIO,
        )
    }

    /** Окно изнутри рамы: по нему летит НЛО и за него не должен вылезать. */
    val WindowHole = RelRect(0.4278f, 0.0854f, 0.8806f, 0.3542f)
}
